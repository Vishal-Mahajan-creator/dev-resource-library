public class Array_1 
{
    public static void main(String[] args)
    {
        int id[]={1,2,3,4,5};
        String name[]={"vishal","Kaustubh","Vaibhav","Shreenath","Akash"};
        float salary[]={10000.665f,23135.658f,3456.65f,11224.536f,3656.535367f};

        for(int i=0;i<id.length;i++)
        {
            System.out.println("The Id of Person:-" + id[i]);
            System.out.println("The name of Person:-" + name[i]);
            System.out.println("The salary of Person:-" + salary[i]);
            System.out.println("\n");
        }
      
    }
}
    

